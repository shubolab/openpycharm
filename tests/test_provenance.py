import hashlib
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from provenance import source_inputs, verify_source_inputs


class SourceProvenanceTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        (self.root / "scripts").mkdir()
        (self.root / "product/resources").mkdir(parents=True)
        (self.root / "plugins/http-client/src").mkdir(parents=True)
        self.files = {"scripts/package.py": b"print('build')\n", "product/resources/icon.svg": b"<svg/>\n",
                      "product/platform.lock.json": b'{"pin":"fixed"}\n',
                      "plugins/http-client/src/Client.kt": b"class Client\n",
                      "plugins/http-client/compiler.lock.json": b'{"sha256":"pinned"}\n',
                      "requirements-build.txt": b"Pillow==12.1.0\n", "LICENSE": b"license\n", "NOTICE": b"notice\n"}
        for relative, data in self.files.items():
            (self.root / relative).write_bytes(data)
        self.manifest = {"sourceInputs": source_inputs(self.root)}

    def test_valid_inventory_covers_exact_inputs_and_ignores_python_cache(self):
        cache = self.root / "scripts/__pycache__"
        cache.mkdir()
        (cache / "package.cpython-312.pyc").write_bytes(b"generated bytecode")
        expected = {name: hashlib.sha256(data).hexdigest() for name, data in self.files.items()}
        self.assertEqual(source_inputs(self.root), expected)
        self.assertIsNone(verify_source_inputs(self.manifest, self.root))

    def test_mutating_any_source_or_notice_invalidates_product(self):
        for name, original in self.files.items():
            with self.subTest(input=name):
                path = self.root / name
                path.write_bytes(original + b"changed")
                with self.assertRaisesRegex(ValueError, "stale.*changed"):
                    verify_source_inputs(self.manifest, self.root)
                path.write_bytes(original)

    def test_added_and_removed_files_invalidate_exact_inventory(self):
        added = self.root / "scripts/new-repair.py"
        added.write_text("new input")
        with self.assertRaisesRegex(ValueError, "stale.*added: scripts/new-repair.py"):
            verify_source_inputs(self.manifest, self.root)
        added.unlink()
        removed = self.root / "product/resources/icon.svg"
        removed.unlink()
        with self.assertRaisesRegex(ValueError, "stale.*removed: product/resources/icon.svg"):
            verify_source_inputs(self.manifest, self.root)

    def test_file_and_directory_symlinks_are_rejected_without_following_them(self):
        external = self.root / "external"
        external.mkdir()
        target = external / "private.txt"
        target.write_text("must not be inventoried")
        for name, destination, directory in (("linked-file", target, False), ("linked-directory", external, True)):
            link = self.root / "scripts" / name
            try:
                link.symlink_to(destination, target_is_directory=directory)
            except OSError as error:
                self.skipTest(f"Host cannot create test symlinks: {error}")
            try:
                with self.subTest(link=name), self.assertRaisesRegex(ValueError, "symlink"):
                    source_inputs(self.root)
            finally:
                link.unlink()
        self.assertEqual(target.read_text(), "must not be inventoried")
        self.assertNotIn("external/private.txt", source_inputs(self.root))

    def test_required_notice_cannot_be_replaced_by_a_symlink(self):
        external = self.root / "outside-notice.txt"
        external.write_text("outside notice")
        notice = self.root / "NOTICE"
        notice.unlink()
        try:
            notice.symlink_to(external)
        except OSError as error:
            self.skipTest(f"Host cannot create test symlinks: {error}")
        with self.assertRaisesRegex(ValueError, "regular file"):
            source_inputs(self.root)

    def test_missing_or_malformed_manifest_does_not_select_files_to_read(self):
        for inventory in (None, {}, {"../outside": "not-a-digest"}, {0: "0" * 64}):
            with self.subTest(inventory=inventory), self.assertRaisesRegex(ValueError, "valid sourceInputs"):
                verify_source_inputs({"sourceInputs": inventory}, self.root)
        # A syntactically valid forged path is compared with the source inventory,
        # never used as a path to open outside the selected source root.
        with self.assertRaisesRegex(ValueError, "stale"):
            verify_source_inputs({"sourceInputs": {"../outside": "0" * 64}}, self.root)


if __name__ == "__main__":
    unittest.main()
